def _read_env_file(path: Path) -> dict[str, str]:
    """Parse a .env file with python-dotenv (the one documented dialect).

    docker compose ``--env-file`` and this loader must agree on every value;
    python-dotenv's semantics (``export`` prefixes, quoting, inline comments
    only outside quotes) match compose for the constructs ``.env.example``
    documents. Keys without a value (bare ``KEY`` lines) are skipped.
    """
    try:
        with path.open("r", encoding="utf-8") as stream:
            raw = dotenv_values(stream=stream)
    except (OSError, UnicodeDecodeError) as exc:
        raise ConfigError(f"env file unreadable: {path}: {exc}") from exc
    return {key: value for key, value in raw.items() if value is not None}


def _validate_worktree_env(path: Path, values: dict[str, str]) -> None:
    """Refuse any ``.env.worktree`` that is not a complete, coherent
    generated file — the same schema ``infra/worktree_stack.py``'s
    ``validate_env_file`` applies, minus its slug/directory check (the
    loader does not know the checkout). Each refusal names the file and the
    offending key.
    """
    remedy = (
        ".env.worktree is generated whole by 'make worktree'; delete"
        f" {path} and run 'make worktree-provision' in that worktree"
    )
    foreign = [key for key in values if key not in WORKTREE_ENV_KEYS]
    if foreign:
        raise ConfigError(
            f"{path}: {', '.join(foreign)} is not a stack key —"
            f" {WORKTREE_ENV_FILENAME} carries only"
            f" {', '.join(sorted(WORKTREE_ENV_KEYS))}"
        )
    missing = [key for key in WORKTREE_ENV_KEY_ORDER if key not in values]
    if missing:
        raise ConfigError(f"{path}: missing {', '.join(missing)} — {remedy}")
    blank = [key for key in WORKTREE_ENV_KEY_ORDER if not values[key].strip()]
    if blank:
        raise ConfigError(f"{path}: {', '.join(blank)} is blank — {remedy}")
    if not _STACK_NAME_RE.match(values[STACK_NAME_KEY]):
        raise ConfigError(
            f"{path}: {STACK_NAME_KEY} is {values[STACK_NAME_KEY]!r}, not a"
            f" meetingminer-<slug> stack name — {remedy}"
        )
    ports: dict[str, int] = {}
    for key in STACK_PORT_KEYS:
        raw = values[key]
        if not (raw.isascii() and raw.isdigit()) or not 1 <= int(raw) <= 65535:
            raise ConfigError(
                f"{path}: {key} must be an integer port in 1..65535, got"
                f" {raw!r} — {remedy}"
            )
        ports[key] = int(raw)
    duplicated = [
        key for key in STACK_PORT_KEYS
        if list(ports.values()).count(ports[key]) > 1
    ]
    if duplicated:
        raise ConfigError(
            f"{path}: {', '.join(duplicated)} declare the same port — {remedy}"
        )
    clashing = [key for key in STACK_PORT_KEYS if ports[key] in _MAIN_STACK_PORTS]
    if clashing:
        raise ConfigError(
            f"{path}: {', '.join(clashing)} names a main-checkout default"
            f" port — a worktree on it would reach the main stack — {remedy}"
        )
    if not _STACK_ID_RE.match(values[STACK_ID_KEY]):
        raise ConfigError(
            f"{path}: {STACK_ID_KEY} must be 12 lowercase hex characters,"
            f" got {values[STACK_ID_KEY]!r} — {remedy}"
        )
    expected_neo4j = f"bolt://localhost:{ports['MM_NEO4J_TEST_BOLT_PORT']}"
    if values[TEST_NEO4J_URI_KEY] != expected_neo4j:
        raise ConfigError(
            f"{path}: {TEST_NEO4J_URI_KEY} is {values[TEST_NEO4J_URI_KEY]!r},"
            f" not the declared test port's {expected_neo4j!r} — {remedy}"
        )
    expected_meili = f"http://localhost:{ports['MM_MEILI_TEST_PORT']}"
    if values[TEST_MEILI_URL_KEY] != expected_meili:
        raise ConfigError(
            f"{path}: {TEST_MEILI_URL_KEY} is {values[TEST_MEILI_URL_KEY]!r},"
            f" not the declared test port's {expected_meili!r} — {remedy}"
        )


def validated_worktree_env(env_path: Path) -> dict[str, str]:
    """The validated ownership record beside ``env_path``, or an empty dict.

    Unlike :func:`merged_env`, this returns the file's declarations before
    process-environment precedence. Directory-ownership guards must compare
    this immutable source record, not an overridable merged value.
    """
    worktree_env = env_path.parent / WORKTREE_ENV_FILENAME
    if not worktree_env.is_file():
        return {}
    try:
        lines = worktree_env.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError) as exc:
        raise ConfigError(f"env file unreadable: {worktree_env}: {exc}") from exc
    seen: set[str] = set()
    for line_number, raw in enumerate(lines, start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _WORKTREE_ASSIGNMENT_RE.fullmatch(raw)
        if match is None:
            raise ConfigError(
                f"{worktree_env}: invalid line {line_number}: {raw!r} — the"
                " file carries data assignments only, never Make directives"
            )
        key = match.group(1)
        if key in seen:
            raise ConfigError(
                f"{worktree_env}: duplicate {key} on line {line_number} —"
                " each ownership key must be assigned exactly once"
            )
        seen.add(key)
    values = _read_env_file(worktree_env)
    _validate_worktree_env(worktree_env, values)
    return values


def merged_env(env_path: Path) -> dict[str, str]:
    """The environment the loader sees: ``.env``, then ``.env.worktree``
    beside it, then the process environment — each overriding the last.

    ``.env`` is the secrets file ``env_path`` names (in a git worktree, a
    symlink to the main checkout's). ``.env.worktree`` is looked up beside
    that *path*, not its target, so each worktree reads its own generated
    file; when it exists it must be a complete, coherent generated file
    (exactly :data:`WORKTREE_ENV_KEYS`, a ``meetingminer-<slug>`` name,
    seven valid distinct non-default ports, the incarnation id, twin URLs
    derived from the declared test ports — see
    :func:`_validate_worktree_env`), and ``.env`` may carry none of the
    stack name or port keys — each violation is a named
    :class:`ConfigError`, so a secret can never be overridden from the
    worktree file, a port can never be set where the Makefile does not
    look, and a truncated file can never silently leave a worktree on the
    main checkout's stack. The process environment wins over both — except that a blank
    process-env value never masks a real file value (finding 15: a stray
    `export VAR=` in a shell profile must not blank out a secret). docker
    compose is given the same two files in the same order; the Makefile
    reads the stack keys from ``.env.worktree`` alone.
    """
    merged: dict[str, str] = {}
    if env_path.is_file():
        base = _read_env_file(env_path)
        misplaced = [key for key in (STACK_NAME_KEY, *STACK_PORT_KEYS) if key in base]
        if misplaced:
            raise ConfigError(
                f"{env_path}: {', '.join(misplaced)} — stack keys belong in"
                f" {WORKTREE_ENV_FILENAME} (written by 'make worktree'), never in .env"
            )
        merged.update(base)
    merged.update(validated_worktree_env(env_path))
    for key, value in os.environ.items():
        if value.strip() or key not in merged:
            merged[key] = value
    return merged


def _env_port(env: dict[str, str], name: str) -> int | None:
    """One port override: unset or blank is None; anything else must be an
    integer in 1..65535 or the load fails naming the variable."""
    raw = env.get(name, "").strip()
    if not raw:
        return None
    # ASCII digits only: int() would also accept "+5", "1_000" and other
    # scripts' digits, none of which compose reads the same way.
    port = int(raw) if raw.isascii() and raw.isdigit() else 0
    if not 1 <= port <= 65535:
        raise ConfigError(
            f"{name} must be an integer port in 1..65535, got {raw!r}"
        )
    return port


def _with_port(url: str, port: int, name: str) -> str:
    """``url`` with its port replaced (or added) — scheme, userinfo and the
    host text kept verbatim (case, IPv6 brackets)."""
    try:
        parts = urlsplit(url)
        hostname = parts.hostname
    except ValueError as exc:
        raise ConfigError(f"{name}: cannot apply to endpoint {url!r}: {exc}") from exc
    if not parts.scheme or not hostname:
        raise ConfigError(
            f"{name}: cannot apply to endpoint {url!r}: scheme and host are required"
        )
    userinfo, at, hostport = parts.netloc.rpartition("@")
    if hostport.startswith("["):
        host_text = hostport[: hostport.index("]") + 1]
    else:
        host_text = hostport.split(":", 1)[0]
    return urlunsplit(
        (parts.scheme, f"{userinfo}{at}{host_text}:{port}", parts.path, parts.query, parts.fragment)
    )


def _apply_stack_overrides(settings: "Settings", env: dict[str, str]) -> None:
    """Point the three store endpoints at a private stack's ports (11.2).

    Inactive when none of the variables is set, so config.yaml alone still
    describes the main checkout's stack. Each override rebuilds its store
    model through validation, the same way the test session repoints the
    twins, so the result is as checked as a value read from the file.
    """
    stores = settings.stores
    postgres_port = _env_port(env, POSTGRES_PORT_ENV)
    if postgres_port is not None:
        stores.postgres = PostgresStore.model_validate(
            {**stores.postgres.model_dump(), "port": postgres_port}
        )
    neo4j_port = _env_port(env, NEO4J_BOLT_PORT_ENV)
    if neo4j_port is not None:
        stores.neo4j = Neo4jStore.model_validate(
            {
                **stores.neo4j.model_dump(),
                "uri": _with_port(stores.neo4j.uri, neo4j_port, NEO4J_BOLT_PORT_ENV),
            }
        )
    meili_port = _env_port(env, MEILI_PORT_ENV)
    if meili_port is not None:
        stores.meilisearch = MeilisearchStore.model_validate(
            {
                **stores.meilisearch.model_dump(),
                "url": _with_port(stores.meilisearch.url, meili_port, MEILI_PORT_ENV),
            }
        )


def _load_secrets(merged: dict[str, str]) -> Secrets:
    def get(key: str) -> str | None:
        value = merged.get(key, "").strip()
        return value or None

    def root(name: str) -> Path | None:
        """Read one configured root: absolute, ``~`` expanded here and nowhere else.

        Both roots (`MM_CONTENT_ROOT`, `MM_DROPS_ROOT`) go through this one
        function so the two anchors of `storage-layout.md` §1 can never
        disagree about what a configured root value means.
        """
        raw = get(name)
        if raw is None:
            return None
        try:
            # expanduser() raises RuntimeError for an unresolvable ~user.
            expanded = Path(raw).expanduser()
        except RuntimeError as exc:
            raise ConfigError(f"{name} could not be expanded: {raw!r}: {exc}") from exc
        if not expanded.is_absolute():
            raise ConfigError(f"{name} must be an absolute path: {raw!r}")
        return expanded.resolve()

    return Secrets(
        mm_content_root=root("MM_CONTENT_ROOT"),
        mm_drops_root=root("MM_DROPS_ROOT"),
        mm_publish_root=root("MM_PUBLISH_ROOT"),
        anthropic_api_key=get("ANTHROPIC_API_KEY"),
        openai_api_key=get("OPENAI_API_KEY"),
        openrouter_api_key=get("OPENROUTER_API_KEY"),
        postgres_password=get("POSTGRES_PASSWORD"),
        neo4j_password=get("NEO4J_PASSWORD"),
        meili_master_key=get("MEILI_MASTER_KEY"),
    )


