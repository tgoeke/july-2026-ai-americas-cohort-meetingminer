"""Shared typed loader for config.yaml + .env secrets (AD-10).

Both the api and the worker load configuration through this module and only
this module. Every adapter binding comes from the single versioned root
``config.yaml``; environment variables (``.env``) carry secrets, the root
locations, and — for a git worktree with a private compose stack (story
11.2) — the host ports that stack publishes: ``MM_POSTGRES_PORT``,
``MM_NEO4J_BOLT_PORT`` and ``MM_MEILI_PORT`` replace only the port of the
configured store endpoint (host, scheme and credentials stay in
``config.yaml``). Any load failure raises :class:`ConfigError` — callers exit
non-zero; there is no silent default.

File resolution never derives from ``__file__`` (the wheel ships this module
far from the repo): ``config.yaml`` resolves from ``MM_CONFIG_PATH`` when
set, else ``./config.yaml`` relative to the current working directory; the
``.env`` file resolves from ``MM_ENV_PATH``, else ``./.env``; a
``.env.worktree`` beside it (generated by ``make worktree``, never by hand)
is read after it and overrides it, and the process environment overrides
both — see :func:`merged_env`. The ``docs/`` tree (e.g. the source-drop
schema) anchors off the resolved config file's parent directory — one
anchor, no second mechanism.

The ``.env`` dialect is python-dotenv's, which matches docker compose
``--env-file`` semantics for the constructs we document in ``.env.example``
(``export`` prefixes, quoting, inline comments). Comments are never stripped
from quoted values.
"""

