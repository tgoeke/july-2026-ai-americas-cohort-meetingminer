#!/usr/bin/env node
/*
 * grab-teams-transcript.js
 * ------------------------------------------------------------------
 * Grab a full Microsoft Teams / Stream meeting transcript from the CLI.
 *
 * Why a browser (and not curl): the transcript is behind your SSO login
 * and is rendered by client-side JS from a token-authenticated API, so
 * there is no plain URL to fetch. This drives a real logged-in Chromium,
 * opens the Transcript panel, scrolls the (virtualized) list, harvests
 * every turn, de-duplicates the overlapping passes, and writes clean
 * "[m:ss] Speaker: text" output.
 *
 * SETUP (once):
 *   npm init -y
 *   npm i playwright
 *   npx playwright install chromium
 *
 * FIRST RUN — log in once (a browser window opens; sign in with CONTOSO SSO,
 * land on any Teams/Stream page, then press Enter in the terminal):
 *   node grab-teams-transcript.js --login
 * Your session is saved to ./.transcript-profile so later runs reuse it.
 *
 * GRAB A MEETING (transcript + video):
 *   node grab-teams-transcript.js "<stream-url>"
 *     -> creates/reuses "<Meeting Title>/<M.D.YY>/" — one folder per SERIES,
 *        one subfolder per OCCURRENCE — and writes
 *        "<M.D.YY> <Meeting Title>.txt" + ".mp4" + ".md" + " action items.md"
 *        inside it, so occurrences of a recurring meeting can never overwrite
 *        each other (only a re-run of the same occurrence does). For recordings
 *        you own, the transcript downloads via the media API (exact
 *        timestamps; original .vtt + .docx saved alongside) and scraping is
 *        only the fallback. The .md docs are
 *        generated by Ollama (gpt-oss:120b on 10.77.0.52 — override with
 *        OLLAMA_URL / OLLAMA_MODEL): an architecture summary
 *        (arch_summary_prompt.md) and an owner-grouped action-items
 *        checklist (action_items_prompt.md).
 *   node grab-teams-transcript.js "<stream-url>" --no-video      # transcript only
 *   node grab-teams-transcript.js "<stream-url>" --no-summary    # skip the Ollama-generated docs
 *   node grab-teams-transcript.js "<stream-url>" out.txt         # transcript to a specific file
 *   node grab-teams-transcript.js "<stream-url>" -               # transcript to stdout
 *   node grab-teams-transcript.js "<stream-url>" --headful       # show the browser
 *   node grab-teams-transcript.js "<stream-url>" --date 7.14.26  # force the meeting date
 *   node grab-teams-transcript.js --summarize "<file.txt>"       # regenerate both docs for an existing transcript
 *   node grab-teams-transcript.js --replay [--dry-run]           # re-pull every URL in pulls.jsonl
 *
 * MEETINGMINER SOURCE DROPS: after a successful single-recording pull the
 * occurrence is also emitted as a write-once source drop and handed to the
 * ingestion API (see emit-drop.js). It never fails the pull.
 *   node grab-teams-transcript.js "<stream-url>" --no-emit       # skip the drop + intake entirely
 *   node grab-teams-transcript.js "<stream-url>" --drops <dir>   # drops folder      [MM_DROPS_ROOT]
 *   node grab-teams-transcript.js "<stream-url>" --api <url>     # api base url      [MM_API_URL]
 *   node grab-teams-transcript.js "<stream-url>" --corpus scripted  # eval-corpus tag [MM_CORPUS]
 *   node emit-drop.js --all                                      # backfill the whole archive
 *
 * Every URL is appended to pulls.jsonl and each occurrence folder gets a
 * _source.json, so the library can be rebuilt with --replay after a fix.
 *
 * TIP: use the Stream URL (the page you get from "Watch in browser"),
 * e.g. https://<tenant>-my.sharepoint.com/.../stream.aspx?id=...
 * ------------------------------------------------------------------
 */
